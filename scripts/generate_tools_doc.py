#!/usr/bin/env python3
"""Generate docs/tools.md from the tools the server actually registers.

Builds the same FastMCP app main() builds (see generate_dxt_tools.py) against
a mocked Garmin client, so the list cannot drift from the code.

    uv run python scripts/generate_tools_doc.py           # rewrite docs/tools.md
    uv run python scripts/generate_tools_doc.py --check   # exit 1 when stale
"""
import asyncio
import inspect
import re
import sys
from pathlib import Path
from unittest.mock import MagicMock

from mcp.server.fastmcp import FastMCP

from garmin_mcp import tool_annotations
from garmin_mcp.tool_profiles import TOOL_PROFILES

sys.path.insert(0, str(Path(__file__).resolve().parent))
from generate_dxt_tools import MODULES, _first_line  # noqa: E402

DOC_PATH = Path(__file__).resolve().parent.parent / "docs" / "tools.md"

MODULE_TITLES = {
    "activity_management": "Activities",
    "health_wellness": "Health and wellness",
    "user_profile": "User profile",
    "devices": "Devices",
    "gear_management": "Gear",
    "weight_management": "Weight and body composition",
    "challenges": "Challenges and badges",
    "training": "Training and performance",
    "workouts": "Workouts",
    "data_management": "Data management",
    "womens_health": "Women's health",
    "nutrition": "Nutrition",
    "workout_builders": "Workout builders",
    "courses": "Courses",
    "activity_analysis": "Activity analysis",
    "calendar_events": "Calendar",
    "race_events": "Race events",
    "health_extra": "Health (extended)",
    "metrics_extra": "Performance metrics (extended)",
    "training_extra": "Training plans, calendar and courses (extended)",
    "activities_extra": "Activities (extended)",
    "equipment_extra": "Workout library, body and gear (extended)",
}


def _effect(name: str) -> str:
    if name in tool_annotations.READ_ONLY_TOOLS:
        return "read"
    if name in tool_annotations.DESTRUCTIVE_TOOLS:
        return "write (destructive)"
    if name in tool_annotations.ADDITIVE_TOOLS:
        return "write"
    return "unclassified"


# A tool that talks to Garmin Connect through the generic client instead of a
# python-garminconnect method. Garmin does not document these endpoints, so
# these tools are the first to break when Garmin changes something.
_DIRECT_CALL = re.compile(r"connectapi|\.client\.(get|post|put|delete|request)\(|\.garth\.")


_CALL = re.compile(r"\b([A-Za-z_]\w*)\(")


def _source_with_helpers(fn, seen: set) -> str:
    """Source of fn plus the garmin_mcp helper functions it calls, recursively."""
    if id(fn) in seen:
        return ""
    seen.add(id(fn))
    try:
        source = inspect.getsource(fn)
    except (OSError, TypeError):
        return ""
    scope = dict(getattr(fn, "__globals__", {}))
    scope.update(inspect.getclosurevars(fn).nonlocals)
    for name in set(_CALL.findall(source)):
        helper = scope.get(name)
        if inspect.isfunction(helper) and helper.__module__.startswith("garmin_mcp"):
            source += _source_with_helpers(helper, seen)
    return source


def _direct(app: FastMCP, name: str) -> str:
    source = _source_with_helpers(app._tool_manager.get_tool(name).fn, set())
    return "yes" if _DIRECT_CALL.search(source) else ""


def _profiles(name: str) -> str:
    return ", ".join(
        profile for profile, tools in TOOL_PROFILES.items() if tools and name in tools
    )


async def _collect() -> tuple[FastMCP, list[tuple[str, list]]]:
    """The app and [(module name, [tool, ...]), ...] in registration order."""
    mock_client = MagicMock()
    app = FastMCP("Slurp garmin-mcp")
    sections, seen = [], set()
    for module in MODULES:
        module.configure(mock_client)
        module.register_tools(app)
        tools = [t for t in await app.list_tools() if t.name not in seen]
        seen.update(t.name for t in tools)
        sections.append((module.__name__.rsplit(".", 1)[-1], sorted(tools, key=lambda t: t.name)))
    return app, sections


def _cell(text: str) -> str:
    return text.replace("|", "\\|")


def render() -> str:
    app, sections = asyncio.run(_collect())
    total = sum(len(tools) for _, tools in sections)
    writes = sum(1 for _, tools in sections for t in tools if _effect(t.name) != "read")
    lines = [
        "# Tools",
        "",
        "<!-- Generated by scripts/generate_tools_doc.py. Do not edit by hand. -->",
        "",
        f"Slurp garmin-mcp registers **{total} tools**; {writes} of them change data "
        "(in Garmin Connect, or files on the server).",
        "",
        "- **Effect** is what the server reports to the client as MCP tool annotations: "
        "`read`, `write` (adds or changes something) or `write (destructive)` "
        "(deletes or overwrites).",
        "- **Profiles** lists the `GARMIN_TOOL_PROFILE` values that include the tool; "
        "every tool is in the default `all`. See [configuration.md](configuration.md#tool-filtering).",
        "- **Direct** marks tools that call a Garmin Connect endpoint themselves instead of "
        "going through a [python-garminconnect](https://github.com/cyberjunky/python-garminconnect) "
        "method. Garmin does not document its endpoints; these tools are the most likely to "
        "break when Garmin changes something.",
        "",
        "| Area | Tools |",
        "|---|---:|",
    ]
    for module, tools in sections:
        title = MODULE_TITLES.get(module, module)
        anchor = title.lower().replace("'", "").replace(" ", "-")
        lines.append(f"| [{title}](#{anchor}) | {len(tools)} |")
    for module, tools in sections:
        lines += ["", f"## {MODULE_TITLES.get(module, module)}", "",
                  f"Module `garmin_mcp.{module}`.", "",
                  "| Tool | Effect | Profiles | Direct | Description |", "|---|---|---|---|---|"]
        for tool in tools:
            lines.append(
                f"| `{tool.name}` | {_effect(tool.name)} | {_profiles(tool.name)} | "
                f"{_direct(app, tool.name)} | "
                f"{_cell(_first_line(tool.description))} |"
            )
    return "\n".join(lines) + "\n"


def main() -> None:
    content = render()
    if "--check" in sys.argv[1:]:
        if not DOC_PATH.exists() or DOC_PATH.read_text() != content:
            print(f"{DOC_PATH} is out of date; run scripts/generate_tools_doc.py", file=sys.stderr)
            sys.exit(1)
        print(f"{DOC_PATH} is up to date")
        return
    DOC_PATH.parent.mkdir(exist_ok=True)
    DOC_PATH.write_text(content)
    print(f"Wrote {DOC_PATH}")


if __name__ == "__main__":
    main()
